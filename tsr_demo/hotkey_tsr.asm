; ============================================================================
; hotkey_tsr.asm - TSR 热键演示程序
; ============================================================================
; 功能: 按 ESC 键时在屏幕中央显示弹窗消息
; 原理: 钩住 INT 09h (键盘硬件中断)，在每次按键时检查是否是热键
;
; 编译: nasm -f bin -o HOTKEY.COM hotkey_tsr.asm
; 运行: 在 DOS/DOSBox 中执行 HOTKEY.COM
;
; ============================================================================
; DOS/BIOS 中断服务速查表 (本程序使用的):
; ============================================================================
;
; INT 21h - DOS 服务中断
; ─────────────────────────────────────────
;   AH=09h: 显示字符串
;           输入: DS:DX = 字符串地址 (以 '$' 结尾)
;
;   AH=25h: 设置中断向量
;           输入: AL = 中断号, DS:DX = 新处理程序地址
;
;   AH=35h: 获取中断向量
;           输入: AL = 中断号
;           输出: ES:BX = 当前处理程序地址
;
;   AH=31h: 终止并驻留 (TSR)
;           输入: DX = 驻留内存大小 (段落数)
;
; INT 09h - 键盘硬件中断 (IRQ 1)
; ─────────────────────────────────────────
;   说明: 这不是服务调用，而是硬件中断!
;         每当键盘控制器检测到按键 (按下或释放)，就会触发 INT 09h
;         BIOS 的默认处理程序会:
;         1. 从端口 0x60 读取扫描码
;         2. 转换为 ASCII 并放入键盘缓冲区
;         3. 发送 EOI (End Of Interrupt) 给 PIC
;
;   扫描码: 键盘发送的是"扫描码"，不是 ASCII
;           按下键: 扫描码 (如 ESC = 0x01)
;           释放键: 扫描码 + 0x80 (如 ESC 释放 = 0x81)
;
;   常用扫描码:
;           ESC = 0x01,  1 = 0x02,  2 = 0x03, ... 0 = 0x0B
;           Q = 0x10,    W = 0x11,  E = 0x12, ...
;           A = 0x1E,    S = 0x1F,  D = 0x20, ...
;           Space = 0x39
;           F1 = 0x3B,   F2 = 0x3C, ... F10 = 0x44
;           F11 = 0x57,  F12 = 0x58
;
; INT 10h - BIOS 视频服务
; ─────────────────────────────────────────
;   AH=02h: 设置光标位置
;           输入: BH = 页号, DH = 行, DL = 列
;
;   AH=03h: 获取光标位置
;           输入: BH = 页号
;           输出: DH = 行, DL = 列, CH/CL = 光标形状
;
; I/O 端口
; ─────────────────────────────────────────
;   0x60 - 键盘数据端口
;          读取: 获取扫描码
;          这是 8042 键盘控制器的输出缓冲区
;
; ============================================================================

org 100h                        ; COM 文件格式

section .text

; ============================================================================
; 程序入口点 - 安装 TSR
; ============================================================================
start:
    ; ─────────────────────────────────────────────────────────────────────────
    ; 第 1 步: 显示安装消息
    ; ─────────────────────────────────────────────────────────────────────────
    mov ah, 09h                 ; INT 21h/AH=09h: 显示字符串
    mov dx, install_msg         ; DS:DX = 字符串地址
    int 21h

    ; ─────────────────────────────────────────────────────────────────────────
    ; 第 2 步: 获取并保存原 INT 09h 向量
    ; ─────────────────────────────────────────────────────────────────────────
    mov ax, 3509h               ; AH=35h: 获取中断向量
                                ; AL=09h: INT 09h (键盘中断)
    int 21h                     ; ES:BX = 原处理程序地址
    mov [old_int09_off], bx     ; 保存偏移
    mov [old_int09_seg], es     ; 保存段

    ; ─────────────────────────────────────────────────────────────────────────
    ; 第 3 步: 设置新的 INT 09h 处理程序
    ; ─────────────────────────────────────────────────────────────────────────
    mov ax, 2509h               ; AH=25h: 设置中断向量
                                ; AL=09h: INT 09h
    mov dx, new_int09           ; DS:DX = 新处理程序地址
    int 21h

    ; ─────────────────────────────────────────────────────────────────────────
    ; 第 4 步: 终止并驻留
    ; ─────────────────────────────────────────────────────────────────────────
    mov ax, 3100h               ; AH=31h: 终止并驻留
    mov dx, (resident_end - start + 256 + 15) / 16  ; 驻留段落数
    int 21h

; ============================================================================
; 驻留代码段 - 每次按键都会执行这里的代码
; ============================================================================

new_int09:
    ; ─────────────────────────────────────────────────────────────────────────
    ; 保存所有寄存器 (中断处理程序的基本礼仪)
    ; ─────────────────────────────────────────────────────────────────────────
    push ax
    push bx
    push cx
    push dx
    push si
    push di
    push ds
    push es

    ; ─────────────────────────────────────────────────────────────────────────
    ; 从键盘控制器读取扫描码
    ; ─────────────────────────────────────────────────────────────────────────
    ; 端口 0x60 是 8042 键盘控制器的输出缓冲区
    ; 每次按键 (按下或释放) 都会在这里产生一个扫描码
    ;
    ; 注意: 我们只是"偷看"扫描码，不消费它
    ;       原 BIOS 处理程序会真正处理这个按键
    in al, 60h                  ; AL = 扫描码

    ; ─────────────────────────────────────────────────────────────────────────
    ; 检查是否是我们的热键 (ESC 键)
    ; ─────────────────────────────────────────────────────────────────────────
    ; ESC 键的扫描码是 0x01
    ; 如果是 0x81 (0x01 + 0x80)，那是 ESC 键释放，我们不处理
    cmp al, 01h                 ; 是 ESC 键按下吗?
    jne .chain                  ; 不是，跳转到链式调用

    ; ─────────────────────────────────────────────────────────────────────────
    ; ESC 键被按下! 显示弹窗消息
    ; ─────────────────────────────────────────────────────────────────────────
    
    ; 设置 DS 指向我们的数据段
    push cs
    pop ds                      ; DS = CS

    ; ─────────────────────────────────────────────────────────────────────────
    ; 保存当前光标位置 (以便之后恢复)
    ; ─────────────────────────────────────────────────────────────────────────
    mov ah, 03h                 ; INT 10h/AH=03h: 获取光标位置
    mov bh, 0                   ; BH = 页号 (通常是 0)
    int 10h                     ; DH = 行, DL = 列
    push dx                     ; 保存光标位置

    ; ─────────────────────────────────────────────────────────────────────────
    ; 设置 ES 指向视频内存，准备直接写屏
    ; ─────────────────────────────────────────────────────────────────────────
    ; 文本模式视频内存地址:
    ;   彩色: 0xB8000 (段地址 0xB800)
    ;   单色: 0xB0000 (段地址 0xB000)
    mov ax, 0B800h
    mov es, ax                  ; ES = 0xB800 (视频内存段)

    ; ─────────────────────────────────────────────────────────────────────────
    ; 计算弹窗位置: 屏幕中央 (第 10 行，第 25 列)
    ; ─────────────────────────────────────────────────────────────────────────
    ; 视频内存计算公式: 偏移 = 行 × 160 + 列 × 2
    ;   80 列 × 2 字节/字符 = 160 字节/行
    ;   第 10 行第 25 列: 10 × 160 + 25 × 2 = 1600 + 50 = 1650
    mov di, 1650                ; ES:DI 指向显示位置

    ; ─────────────────────────────────────────────────────────────────────────
    ; 绘制弹窗顶部边框 (30 个方块字符)
    ; ─────────────────────────────────────────────────────────────────────────
    ; 视频内存格式: [ASCII 码][属性字节]
    ;   属性字节: 高 4 位 = 背景色, 低 4 位 = 前景色
    ;   0x4F = 0100 1111
    ;          ├──┤ ├──┤
    ;          │    └─ 前景: 1111 = 白色
    ;          └─ 背景: 0100 = 红色
    ;   0xDB = █ (全方块字符)
    mov cx, 30                  ; 循环 30 次
    mov ax, 0x4FDB              ; AH=0x4F (白字红底), AL=0xDB (方块)
.top_border:
    stosw                       ; 写入 [字符][属性]，DI += 2
    loop .top_border            ; CX--, 如果 CX != 0 则循环

    ; ─────────────────────────────────────────────────────────────────────────
    ; 换行: 移动到下一行同一列
    ; ─────────────────────────────────────────────────────────────────────────
    ; 当前 DI 在边框末尾，需要移动到下一行的起始位置
    ; 一行 160 字节，边框宽 30 字符 (60 字节)
    ; 所以跳过 160 - 60 = 100 字节
    add di, 160 - 60

    ; ─────────────────────────────────────────────────────────────────────────
    ; 显示消息文字
    ; ─────────────────────────────────────────────────────────────────────────
    mov si, popup_msg           ; DS:SI 指向消息字符串
    mov ah, 0x4F                ; 属性: 白字红底
.msg_loop:
    lodsb                       ; AL = [DS:SI], SI++
    cmp al, 0                   ; 字符串结束 (以 0 结尾)?
    je .msg_done                ; 是，退出循环
    stosw                       ; 写入 [字符][属性]
    jmp .msg_loop
.msg_done:

    ; ─────────────────────────────────────────────────────────────────────────
    ; 再换行
    ; ─────────────────────────────────────────────────────────────────────────
    add di, 160 - 60

    ; ─────────────────────────────────────────────────────────────────────────
    ; 绘制弹窗底部边框
    ; ─────────────────────────────────────────────────────────────────────────
    mov cx, 30
    mov ax, 0x4FDB
.bottom_border:
    stosw
    loop .bottom_border

    ; ─────────────────────────────────────────────────────────────────────────
    ; 恢复光标位置
    ; ─────────────────────────────────────────────────────────────────────────
    pop dx                      ; DH = 行, DL = 列
    mov ah, 02h                 ; INT 10h/AH=02h: 设置光标位置
    mov bh, 0                   ; 页号
    int 10h

    ; ─────────────────────────────────────────────────────────────────────────
    ; 增加热键触发计数器 (用于调试)
    ; ─────────────────────────────────────────────────────────────────────────
    inc byte [cs:hotkey_count]

.chain:
    ; ─────────────────────────────────────────────────────────────────────────
    ; 恢复所有寄存器
    ; ─────────────────────────────────────────────────────────────────────────
    pop es
    pop ds
    pop di
    pop si
    pop dx
    pop cx
    pop bx
    pop ax

    ; ─────────────────────────────────────────────────────────────────────────
    ; 链式调用原 INT 09h 处理程序
    ; ─────────────────────────────────────────────────────────────────────────
    ; 非常重要! 我们必须调用原 BIOS 处理程序，因为:
    ; 1. 它会处理按键，把字符放入键盘缓冲区
    ; 2. 它会发送 EOI 给 PIC，否则键盘会锁死
    ; 3. 其他 TSR 可能也钩住了 INT 09h
    ;
    ; 使用 JMP FAR 而不是 CALL，因为原处理程序会执行 IRET
    jmp far [cs:old_int09_off]

; ============================================================================
; 驻留数据段
; ============================================================================

old_int09_off   dw 0            ; 原 INT 09h 处理程序偏移
old_int09_seg   dw 0            ; 原 INT 09h 处理程序段
hotkey_count    db 0            ; 热键触发计数 (调试用)

popup_msg:
    db '  ESC Hotkey Activated!   ', 0
    ;  └─ 消息字符串，以 0 结尾 (不是 '$'!)

resident_end:                   ; 驻留部分结束标记

; ============================================================================
; 非驻留部分 - 安装后会被释放
; ============================================================================

install_msg:
    db '=====================================', 13, 10
    db '  TSR Hotkey Demo - Now Installed!   ', 13, 10
    db '=====================================', 13, 10
    db 'Press ESC to see the popup message.', 13, 10
    db 'This TSR hooks INT 09h (Keyboard).', 13, 10
    db '$'                      ; DOS 字符串结束符

; ============================================================================
; 附录: 常用键盘扫描码表
; ============================================================================
;
; 主键盘区:
;   ESC=01  1=02  2=03  3=04  4=05  5=06  6=07  7=08  8=09  9=0A  0=0B  -=0C  ==0D  BS=0E
;   TAB=0F  Q=10  W=11  E=12  R=13  T=14  Y=15  U=16  I=17  O=18  P=19  [=1A  ]=1B  Enter=1C
;   Ctrl=1D A=1E  S=1F  D=20  F=21  G=22  H=23  J=24  K=25  L=26  ;=27  '=28  `=29
;   LShift=2A \=2B Z=2C X=2D C=2E V=2F B=30 N=31 M=32 ,=33 .=34 /=35 RShift=36
;   *=37  Alt=38  Space=39  CapsLock=3A
;
; 功能键:
;   F1=3B  F2=3C  F3=3D  F4=3E  F5=3F  F6=40  F7=41  F8=42  F9=43  F10=44
;   F11=57  F12=58
;
; 释放键 = 按下扫描码 + 0x80
;   例如: ESC 释放 = 0x81, F12 释放 = 0xD8
;
; ============================================================================
