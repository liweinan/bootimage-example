; ============================================================================
; clock_tsr.asm - TSR 时钟演示程序
; ============================================================================
; 功能: 在屏幕右上角显示实时时钟，每秒更新一次
; 原理: 钩住 INT 1Ch (用户定时器中断)，该中断由 BIOS 定时器每秒触发约 18.2 次
;
; 编译: nasm -f bin -o CLOCK.COM clock_tsr.asm
; 运行: 在 DOS/DOSBox 中执行 CLOCK.COM
;
; ============================================================================
; DOS 中断服务速查表 (本程序使用的):
; ============================================================================
;
; INT 21h - DOS 服务中断 (DOS 的核心 API)
; ─────────────────────────────────────────
;   AH=09h: 显示字符串
;           输入: DS:DX = 字符串地址 (以 '$' 结尾)
;           输出: 无
;
;   AH=25h: 设置中断向量
;           输入: AL = 中断号, DS:DX = 新处理程序地址
;           输出: 无
;           说明: 修改中断向量表 (IVT)，将指定中断指向新地址
;
;   AH=35h: 获取中断向量
;           输入: AL = 中断号
;           输出: ES:BX = 当前处理程序地址
;           说明: 读取中断向量表中的当前值
;
;   AH=31h: 终止并驻留 (TSR)
;           输入: AL = 返回码, DX = 驻留内存大小 (段落数，1段落=16字节)
;           输出: 不返回 (程序终止但内存保留)
;           说明: 这是 TSR 的核心! 程序退出但代码留在内存中
;
; INT 1Ah - BIOS 时间服务
; ─────────────────────────────────────────
;   AH=02h: 读取 RTC (实时时钟) 时间
;           输入: 无
;           输出: CH = 小时 (BCD), CL = 分钟 (BCD), DH = 秒 (BCD)
;           说明: BCD 格式: 0x12 表示 12，0x59 表示 59
;
; INT 1Ch - 用户定时器钩子
; ─────────────────────────────────────────
;   说明: 这不是一个服务调用，而是一个"钩子"中断
;         BIOS 的 INT 08h (硬件定时器) 在处理完后会调用 INT 1Ch
;         默认 INT 1Ch 只是一个 IRET (空操作)
;         TSR 可以钩住它来执行定时任务
;   频率: 约 18.2 次/秒 (由 8253 定时器芯片决定)
;
; ============================================================================

org 100h                        ; COM 文件格式
                                ; COM 文件是最简单的 DOS 可执行格式
                                ; 整个程序加载到一个 64KB 段中
                                ; 代码从偏移 100h 开始 (前 256 字节是 PSP)
                                ; PSP (Program Segment Prefix) 包含命令行参数等

section .text

; ============================================================================
; 程序入口点 - 安装 TSR
; ============================================================================
start:
    ; ─────────────────────────────────────────────────────────────────────────
    ; 第 1 步: 显示安装消息
    ; ─────────────────────────────────────────────────────────────────────────
    mov ah, 09h                 ; INT 21h/AH=09h: 显示字符串
    mov dx, install_msg         ; DS:DX 指向要显示的字符串
                                ; 注意: 字符串必须以 '$' 结尾，不是 '\0'!
    int 21h                     ; 调用 DOS 服务

    ; ─────────────────────────────────────────────────────────────────────────
    ; 第 2 步: 获取并保存原 INT 1Ch 向量
    ; ─────────────────────────────────────────────────────────────────────────
    ; 我们需要保存原来的处理程序地址，以便:
    ; 1. 在我们的处理程序结束后调用它 (链式调用)
    ; 2. 如果需要卸载 TSR，可以恢复原向量
    mov ax, 351Ch               ; AH=35h: 获取中断向量
                                ; AL=1Ch: INT 1Ch (用户定时器)
    int 21h                     ; 调用后: ES:BX = 原处理程序地址
    mov [old_int1c_off], bx     ; 保存偏移量
    mov [old_int1c_seg], es     ; 保存段地址

    ; ─────────────────────────────────────────────────────────────────────────
    ; 第 3 步: 设置新的 INT 1Ch 处理程序
    ; ─────────────────────────────────────────────────────────────────────────
    ; 现在我们"钩住"这个中断，让它指向我们的代码
    mov ax, 251Ch               ; AH=25h: 设置中断向量
                                ; AL=1Ch: INT 1Ch
    mov dx, new_int1c           ; DS:DX = 新处理程序地址
                                ; 在 COM 文件中，DS=CS，所以只需要偏移量
    int 21h                     ; 从现在开始，每次 INT 1Ch 都会执行我们的代码!

    ; ─────────────────────────────────────────────────────────────────────────
    ; 第 4 步: 终止并驻留 (TSR 的核心!)
    ; ─────────────────────────────────────────────────────────────────────────
    ; 这是 TSR 的关键: 程序退出，但代码留在内存中
    mov ax, 3100h               ; AH=31h: 终止并驻留
                                ; AL=00h: 返回码 (0 = 成功)
    
    ; 计算需要驻留的内存大小 (以段落为单位，1段落=16字节)
    ; 公式: (驻留代码大小 + PSP大小 + 15) / 16
    ;       +15 是为了向上取整
    mov dx, (resident_end - start + 256 + 15) / 16
    ;        ├─────────────────┤  ├─┤  ├──┤  ├──┤
    ;        │                 │   │    │     └─ 除以 16 得到段落数
    ;        │                 │   │    └─ 向上取整
    ;        │                 │   └─ PSP 大小 (256 字节)
    ;        └─ 驻留代码大小 (从 start 到 resident_end)
    
    int 21h                     ; 程序终止，但内存保留!
                                ; 不会执行到这里之后的代码

; ============================================================================
; 驻留代码段 - 这部分会留在内存中，被 INT 1Ch 触发执行
; ============================================================================

new_int1c:
    ; ─────────────────────────────────────────────────────────────────────────
    ; 中断处理程序必须保存所有使用的寄存器!
    ; 因为我们不知道中断发生时 CPU 在执行什么程序
    ; 如果修改了寄存器但不恢复，会导致那个程序崩溃
    ; ─────────────────────────────────────────────────────────────────────────
    push ax
    push bx
    push cx
    push dx
    push si
    push di
    push ds
    push es

    ; ─────────────────────────────────────────────────────────────────────────
    ; 设置 DS 指向我们的数据段
    ; ─────────────────────────────────────────────────────────────────────────
    ; 在中断发生时，DS 可能指向任何地方
    ; 我们的数据在 CS 段中，所以需要 DS=CS
    push cs
    pop ds                      ; DS = CS

    ; ─────────────────────────────────────────────────────────────────────────
    ; 计数器: 每 18 次中断才更新一次显示 (约 1 秒)
    ; ─────────────────────────────────────────────────────────────────────────
    ; INT 1Ch 每秒触发约 18.2 次，我们不需要每次都更新时钟
    ; 这样可以减少闪烁，也节省 CPU
    inc byte [tick_count]       ; tick_count++
    cmp byte [tick_count], 18   ; 达到 18 次了吗?
    jb .skip_update             ; 如果 < 18，跳过更新
    mov byte [tick_count], 0    ; 重置计数器

    ; ─────────────────────────────────────────────────────────────────────────
    ; 获取 BIOS 时间 (从 RTC 实时时钟芯片读取)
    ; ─────────────────────────────────────────────────────────────────────────
    mov ah, 02h                 ; INT 1Ah/AH=02h: 读取 RTC 时间
    int 1Ah                     ; 调用 BIOS 时间服务
                                ; 返回值 (BCD 格式):
                                ;   CH = 小时 (00h-23h)
                                ;   CL = 分钟 (00h-59h)
                                ;   DH = 秒   (00h-59h)
                                ; BCD 格式: 0x12 表示十进制 12

    ; 保存时间到我们的变量
    mov [bcd_hour], ch
    mov [bcd_min], cl
    mov [bcd_sec], dh

    ; ─────────────────────────────────────────────────────────────────────────
    ; 直接写入视频内存显示时间
    ; ─────────────────────────────────────────────────────────────────────────
    ; 文本模式视频内存布局:
    ;   地址: 0xB8000 (彩色) 或 0xB0000 (单色)
    ;   每个字符占 2 字节: [ASCII码][属性]
    ;   属性字节: 高4位=背景色, 低4位=前景色
    ;   屏幕 80x25，每行 160 字节 (80字符 × 2字节)
    ;
    ; 颜色属性 0x1E = 0001 1110
    ;   高4位 0001 = 蓝色背景
    ;   低4位 1110 = 黄色前景
    
    mov ax, 0B800h              ; 彩色文本模式视频内存段地址
    mov es, ax                  ; ES 指向视频内存

    ; 计算屏幕位置: 第 0 行，第 71 列 (屏幕右上角)
    ; 偏移 = 行 × 160 + 列 × 2 = 0 × 160 + 71 × 2 = 142
    mov di, 142                 ; ES:DI 指向显示位置

    ; 显示 "HH:MM:SS" 格式的时间
    mov al, [bcd_hour]
    call display_bcd            ; 显示小时

    mov al, ':'
    mov ah, 0x1E                ; 黄色前景，蓝色背景
    stosw                       ; 写入字符和属性，DI 自动 +2

    mov al, [bcd_min]
    call display_bcd            ; 显示分钟

    mov al, ':'
    mov ah, 0x1E
    stosw

    mov al, [bcd_sec]
    call display_bcd            ; 显示秒

.skip_update:
    ; ─────────────────────────────────────────────────────────────────────────
    ; 恢复所有寄存器 (与保存时相反的顺序!)
    ; ─────────────────────────────────────────────────────────────────────────
    pop es
    pop ds
    pop di
    pop si
    pop dx
    pop cx
    pop bx
    pop ax

    ; ─────────────────────────────────────────────────────────────────────────
    ; 链式调用原中断处理程序
    ; ─────────────────────────────────────────────────────────────────────────
    ; 这是 TSR 的礼貌做法: 处理完后调用原来的处理程序
    ; 这样多个 TSR 可以共存，形成一个"中断链"
    ; 
    ; 注意: 使用 JMP FAR 而不是 CALL，因为原处理程序会执行 IRET
    ;       如果用 CALL，返回地址会留在栈上导致问题
    ;
    ; 使用 CS: 前缀是因为此时 DS 已经被恢复，可能不指向我们的数据
    jmp far [cs:old_int1c_off]

; ============================================================================
; display_bcd: 显示一个 BCD 数字 (2 位十进制)
; ============================================================================
; 输入: AL = BCD 值 (如 0x12 表示 12)
; 输出: 在 ES:DI 处显示两个 ASCII 字符，DI 增加 4
; ============================================================================
display_bcd:
    push ax
    
    ; 处理高 4 位 (十位数)
    mov ah, al                  ; 保存原值
    shr al, 4                   ; 右移 4 位得到高 4 位
    add al, '0'                 ; 转换为 ASCII ('0'=0x30)
    mov ah, 0x1E                ; 黄色前景，蓝色背景
    stosw                       ; 写入视频内存，DI += 2
    
    ; 处理低 4 位 (个位数)
    pop ax
    and al, 0x0F                ; 屏蔽高 4 位，保留低 4 位
    add al, '0'                 ; 转换为 ASCII
    mov ah, 0x1E
    stosw                       ; 写入视频内存，DI += 2
    
    ret

; ============================================================================
; 驻留数据段 - 这些变量也会留在内存中
; ============================================================================

old_int1c_off   dw 0            ; 原 INT 1Ch 处理程序偏移
old_int1c_seg   dw 0            ; 原 INT 1Ch 处理程序段
tick_count      db 0            ; 定时器计数器 (0-17)
bcd_hour        db 0            ; 当前小时 (BCD)
bcd_min         db 0            ; 当前分钟 (BCD)
bcd_sec         db 0            ; 当前秒   (BCD)

resident_end:                   ; 驻留部分结束标记
                                ; 这个标签用于计算驻留内存大小

; ============================================================================
; 非驻留部分 - 安装后会被 DOS 释放，可以被其他程序覆盖
; ============================================================================
; 把只在安装时使用的数据放在这里可以节省驻留内存

install_msg:
    db '===================================', 13, 10
    ;                                        ├──┴──┤
    ;                                        │  └─ 10 = LF (换行)
    ;                                        └─ 13 = CR (回车)
    db '  TSR Clock Demo - Now Installed!  ', 13, 10
    db '===================================', 13, 10
    db 'Look at the top-right corner of the screen.', 13, 10
    db 'The clock will update every second.', 13, 10
    db 'This TSR hooks INT 1Ch (Timer Tick).', 13, 10
    db '$'                      ; DOS 字符串结束符 (不是 '\0'!)
